#!/usr/bin/env python3
"""Generate scdiag_structs.h: size + VkBool32 member offsets for every struct that can
extend VkDeviceCreateInfo, from the Vulkan registry (vk.xml) and vulkan_core.h."""
import re
import sys
import xml.etree.ElementTree as ET

vkxml, core_h, out = sys.argv[1:4]
core = open(core_h).read()
reg = ET.parse(vkxml).getroot()

entries = []
for t in reg.iter("type"):
    if t.get("category") != "struct" or t.get("alias"):
        continue
    name = t.get("name")
    if "VkDeviceCreateInfo" not in (t.get("structextends") or "").split(","):
        continue
    if not re.search(r"typedef struct %s \{" % name, core):
        continue  # beta / platform-specific header only
    stype, bools = None, []
    for m in t.findall("member"):
        mname = m.find("name").text
        mtype = m.find("type").text
        if mname == "sType":
            stype = m.get("values")
        elif mtype == "VkBool32" and "[" not in "".join(m.itertext()):
            bools.append(mname)
        elif name == "VkPhysicalDeviceFeatures2" and mname == "features":
            bools = ["features"]
    if stype:
        entries.append((name, stype, bools))

feat = []
for t in reg.iter("type"):
    if t.get("name") == "VkPhysicalDeviceFeatures" and t.get("category") == "struct":
        feat = [m.find("name").text for m in t.findall("member")]

with open(out, "w") as f:
    f.write("// generated by gen_structs.py - do not edit\n#pragma once\n#include <stddef.h>\n")
    f.write("typedef struct { int sType; size_t size; const char *name; int nbools;"
            " const size_t *bool_off; const char *const *bool_name; } ScStructInfo;\n")
    for name, stype, bools in entries:
        if bools == ["features"]:
            offs = ["offsetof(%s, features) + offsetof(VkPhysicalDeviceFeatures, %s)" % (name, b) for b in feat]
            names = feat
        else:
            offs = ["offsetof(%s, %s)" % (name, b) for b in bools]
            names = bools
        if names:
            f.write("static const size_t off_%s[] = {%s};\n" % (name, ", ".join(offs)))
            f.write("static const char *const nm_%s[] = {%s};\n" % (name, ", ".join('"%s"' % n for n in names)))
    f.write("static const ScStructInfo sc_structs[] = {\n")
    for name, stype, bools in entries:
        n = len(feat) if bools == ["features"] else len(bools)
        o = "off_%s, nm_%s" % (name, name) if n else "NULL, NULL"
        f.write('    {%s, sizeof(%s), "%s", %d, %s},\n' % (stype, name, name, n, o))
    f.write("};\n#define SC_NSTRUCTS (sizeof sc_structs / sizeof sc_structs[0])\n")
    f.write("static const ScStructInfo *sc_find(int sType) {\n"
            "    for (size_t i = 0; i < SC_NSTRUCTS; i++) if (sc_structs[i].sType == sType) return &sc_structs[i];\n"
            "    return NULL;\n}\n")
print("%d structs" % len(entries))
